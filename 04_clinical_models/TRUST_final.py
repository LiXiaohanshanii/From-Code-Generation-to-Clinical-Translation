# ============================================================
# Figure 4f: decision-curve analysis
# ============================================================
# Net benefit:
#     NB = TP/N - FP/N * pt/(1-pt)
# The clinically relevant interval is defined as the range in
# which the model provides greater net benefit than BOTH the
# treat-all and treat-none strategies.
# ============================================================

thresholds_dca = np.arange(
    0.01,
    1.00,
    0.01
)

n = len(
    y_test
)

prevalence = (
    y_test.mean()
)

# ------------------------------------------------------------
# Treat-all net benefit
# ------------------------------------------------------------

nb_all = (
    prevalence
    -
    (1 - prevalence)
    *
    thresholds_dca
    /
    (1 - thresholds_dca)
)

# ------------------------------------------------------------
# RF model net benefit
# ------------------------------------------------------------

nb_model = []

y_test_array = np.asarray(
    y_test
)

for pt in thresholds_dca:

    pred_positive = (
        y_prob >= pt
    )

    tp_dca = np.sum(
        pred_positive
        &
        (y_test_array == 1)
    )

    fp_dca = np.sum(
        pred_positive
        &
        (y_test_array == 0)
    )

    nb = (
        tp_dca / n
        -
        fp_dca / n
        *
        pt / (1 - pt)
    )

    nb_model.append(
        nb
    )

nb_model = np.asarray(
    nb_model
)

# ============================================================
# Identify threshold ranges where the model outperforms BOTH
# reference strategies
# ============================================================

better_than_both = (
    (nb_model > nb_all)
    &
    (nb_model > 0)
)

def get_continuous_ranges(
    boolean_mask,
    probability_thresholds
):
    """
    Convert a boolean mask into continuous threshold ranges.
    """

    indices = np.where(
        boolean_mask
    )[0]

    if len(indices) == 0:
        return []

    ranges = []

    start = indices[0]
    end = indices[0]

    for idx in indices[1:]:

        if idx == end + 1:

            end = idx

        else:

            ranges.append(
                (
                    probability_thresholds[
                        start
                    ],
                    probability_thresholds[
                        end
                    ]
                )
            )

            start = idx
            end = idx

    ranges.append(
        (
            probability_thresholds[
                start
            ],
            probability_thresholds[
                end
            ]
        )
    )

    return ranges

benefit_ranges = (
    get_continuous_ranges(
        better_than_both,
        thresholds_dca
    )
)

def format_ranges(
    ranges
):

    if not ranges:
        return "None"

    return ", ".join(
        [
            f"{start:.2f}–{end:.2f}"
            for start, end
            in ranges
        ]
    )

benefit_range_text = (
    format_ranges(
        benefit_ranges
    )
)

