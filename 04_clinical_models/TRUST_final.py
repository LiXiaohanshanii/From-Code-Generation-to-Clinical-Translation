# ============================================================
# Formal logistic calibration function
# ============================================================

def calculate_logistic_calibration(
    y_true,
    predicted_probability
):
    """
    Estimate formal calibration intercept and slope using
    individual-level logistic recalibration:
        logit[P(Y=1)] =
        alpha + beta * logit(predicted probability)
    Ideal calibration:
        intercept = 0
        slope = 1
    """

    y_true = np.asarray(
        y_true
    )

    predicted_probability = np.asarray(
        predicted_probability
    )

    eps = 1e-6

    p = np.clip(
        predicted_probability,
        eps,
        1 - eps
    )

    logit_p = np.log(
        p /
        (1 - p)
    ).reshape(
        -1,
        1
    )

    calibration_model = LogisticRegression(
        penalty=None,
        solver="lbfgs",
        max_iter=2000
    )

    calibration_model.fit(
        logit_p,
        y_true
    )

    intercept = (
        calibration_model
        .intercept_[0]
    )

    slope = (
        calibration_model
        .coef_[0][0]
    )

    return (
        intercept,
        slope
    )

